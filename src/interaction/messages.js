/** Localized "no data" marker; replaces the former locale-less constants. */
export function absentText(locale) {
  return translate(locale, 'absent');
}

/** A locale option may be a string or a function so text follows a changing chart locale. */
export function resolveLocale(locale) {
  return typeof locale === 'function' ? locale() : locale;
}
