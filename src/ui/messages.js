/**
 * The locale the chart currently runs with. The surface getter is preferred
 * because it reflects `applyOptions`; hosts without a surface (tests, fakes)
 * fall back to the raw option and finally to the library default.
 */
export function localeOf(chart) {
  return chart?.surface?.locale ?? chart?._options?.locale ?? 'en-US';
}
